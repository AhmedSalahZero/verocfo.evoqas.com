<script setup>
import { sum as sumMoney, discountedLineTotal } from '@/Utils/money'
import { computed } from 'vue'
import { todayLocal } from '@/Utils/dates'
import { Link, useForm } from '@inertiajs/vue3'
import { useI18n } from 'vue-i18n'

const { t } = useI18n()

const props = defineProps({
    salesOrder:   Object,
    issuanceDateLocked: { type: Boolean, default: false },
    customers:    Array,
    projects:     Array,
    currencies:   Array,
    paymentTerms: Array,
    products:     Array,
    uoms:         Array,
})

const isEdit = computed(() => !!props.salesOrder?.id)

// Default currency: controller sorts the company's functional
// currency first in the list, so default to the first entry.
const defaultCurrencyId = computed(() => (props.currencies ?? [])[0]?.id ?? '')

const form = useForm({
    so_code:        props.salesOrder?.so_code       ?? '',
    issuance_date:  props.salesOrder?.issuance_date?.toString().slice(0, 10) ?? todayLocal(),
    project_id:     props.salesOrder?.project_id    ?? '',
    partner_id:     props.salesOrder?.partner_id    ?? '',
    subject:        props.salesOrder?.subject       ?? '',
    description:    props.salesOrder?.description   ?? '',
    currency_id:    props.salesOrder?.currency_id   ?? defaultCurrencyId.value,
    exchange_rate:  props.salesOrder?.exchange_rate ?? '1',
    start_date:     props.salesOrder?.start_date?.toString().slice(0, 10) ?? '',
    end_date:       props.salesOrder?.end_date?.toString().slice(0, 10)   ?? '',
    payment_term_id:props.salesOrder?.payment_term_id ?? '',
    internal_notes: props.salesOrder?.internal_notes ?? '',
    lines: props.salesOrder?.lines?.map(l => ({
        product_id:         l.product_id         ?? '',
        description:        l.description        ?? '',
        quantity:           l.quantity           ?? 1,
        uom_id:             l.uom_id             ?? '',
        unit_price:         l.unit_price         ?? 0,
        discount_pct:       l.discount_pct       ?? 0,
        line_total:         l.line_total         ?? 0,
        revenue_account_id: l.revenue_account_id ?? '',
        cost_center_id:     l.cost_center_id     ?? '',
    })) ?? [{ product_id: '', description: '', quantity: 1, uom_id: '', unit_price: 0, discount_pct: 0, line_total: 0, revenue_account_id: '', cost_center_id: '' }],
})

// Filter projects by selected customer
const filteredProjects = computed(() => {
    if (!form.partner_id) return props.projects ?? []
    return (props.projects ?? []).filter(p => !p.partner_id || p.partner_id == form.partner_id)
})

const soTotal = computed(() => {
    return sumMoney(form.lines.map(l => l.line_total)) // Audit L6: exact (Utils/money.js)
})

function onCustomerChange() {
    // Reset project if it doesn't belong to new customer
    const proj = (props.projects ?? []).find(p => p.id == form.project_id)
    if (proj && proj.partner_id && proj.partner_id != form.partner_id) {
        form.project_id = ''
    }
}

function onProductChange(idx) {
    const line    = form.lines[idx]
    const product = (props.products ?? []).find(p => p.id == line.product_id)
    if (product) {
        if (!line.description) line.description = product.name_en
        // Auto-fill with the product's SALES unit (e.g. Bag), not its
        // internal storage unit — fixed July 2026, same reasoning as
        // the Purchase Order form. Falls back to primary_uom_id only
        // if no sales-specific UOM is set up. Still overridable.
        if (!line.uom_id) line.uom_id = product.sales_uom_id ?? product.primary_uom_id ?? ''
        line.revenue_account_id = product.revenue_account_id ?? ''
    }
    calcLine(idx)
}

function calcLine(idx) {
    const line  = form.lines[idx]
    // Audit L6: same rounding as the server's calcLineTotal() — see Utils/money.js
    line.line_total = discountedLineTotal(line.quantity, line.unit_price, line.discount_pct)
}

function addLine() {
    form.lines.push({
        product_id: '', description: '', quantity: 1, uom_id: '',
        unit_price: 0, discount_pct: 0, line_total: 0, revenue_account_id: '', cost_center_id: '',
    })
}

function removeLine(idx) {
    form.lines.splice(idx, 1)
}

function submit() {
    if (isEdit.value) {
        form.put(route('projects.sales-orders.update', props.salesOrder.id))
    } else {
        form.post(route('projects.sales-orders.store'))
    }
}

function fmt(val) {
    return Number(val || 0).toLocaleString('en-US', { minimumFractionDigits: 2, maximumFractionDigits: 2 })
}

function statusLabel(s) {
    const map = { draft: 'Draft', active: 'Active', on_hold: 'On Hold', closed: 'Closed', cancelled: 'Cancelled' }
    return map[s] ?? s
}
</script>

