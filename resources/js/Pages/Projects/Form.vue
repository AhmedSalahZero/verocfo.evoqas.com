<script setup>
import { computed } from 'vue'
import { Link, useForm } from '@inertiajs/vue3'
import { useI18n } from 'vue-i18n'

const { t } = useI18n()

const props = defineProps({
    project:    Object,
    customers:  Array,
    currencies: Array,
})

const isEdit = computed(() => !!props.project?.id)

// Default currency: the controller sorts the company's functional
// currency first in the list, so default to the first entry.
const defaultCurrencyId = computed(() => (props.currencies ?? [])[0]?.id ?? '')

const form = useForm({
    name_en:        props.project?.name_en        ?? '',
    name_ar:        props.project?.name_ar        ?? '',
    description:    props.project?.description    ?? '',
    partner_id:     props.project?.partner_id     ?? '',
    contract_value: props.project?.contract_value ?? '',
    currency_id:    props.project?.currency_id    ?? defaultCurrencyId.value,
    exchange_rate:  props.project?.exchange_rate  ?? '1',
    start_date:     props.project?.start_date?.toString().slice(0, 10) ?? '',
    end_date:       props.project?.end_date?.toString().slice(0, 10) ?? '',
})

const selectedCurrencyCode = computed(() => {
    const c = (props.currencies ?? []).find(c => c.id == form.currency_id)
    return c?.code ?? 'CCY'
})

function submit() {
    if (isEdit.value) {
        form.put(route('projects.update', props.project.id))
    } else {
        form.post(route('projects.store'))
    }
}

function statusLabel(s) {
    const map = { active: 'Active', on_hold: 'On Hold', closed: 'Closed', cancelled: 'Cancelled' }
    return map[s] ?? s
}
</script>

