<script setup>
import { todayLocal } from '@/Utils/dates'
import { sum as sumMoney, discountedLineTotal } from '@/Utils/money'
import { computed } from 'vue'
import { Link, useForm } from '@inertiajs/vue3'
import { useI18n } from 'vue-i18n'
import SelectBox from '@/Components/SelectBox.vue'

const { t } = useI18n()

const props = defineProps({
    purchaseOrder:    Object,
    issuanceDateLocked: { type: Boolean, default: false },
    suppliers:        Array,
    allowProjectLink: Boolean,
    projects:         Array,
    currencies:       Array,
    functionalCurrencyId: { type: [Number, String], default: null },
    paymentTerms:     Array,
    products:         Array,
    uoms:             Array,
})

const isEdit = computed(() => !!props.purchaseOrder?.id)
// Default to the company's own (functional) currency when known, else the first listed.
const defaultCurrencyId = computed(() => props.functionalCurrencyId ?? (props.currencies ?? [])[0]?.id ?? '')
const isForeignCurrency = computed(() => !!form.currency_id && !!props.functionalCurrencyId && String(form.currency_id) !== String(props.functionalCurrencyId))

const form = useForm({
    po_code:        props.purchaseOrder?.po_code       ?? '',
    issuance_date:  props.purchaseOrder?.issuance_date?.toString().slice(0, 10) ?? todayLocal(),
    project_id:     props.purchaseOrder?.project_id    ?? '',
    partner_id:     props.purchaseOrder?.partner_id    ?? '',
    subject:        props.purchaseOrder?.subject       ?? '',
    description:    props.purchaseOrder?.description   ?? '',
    currency_id:    props.purchaseOrder?.currency_id   ?? defaultCurrencyId.value,
    exchange_rate:  props.purchaseOrder?.exchange_rate ?? '1',
    start_date:     props.purchaseOrder?.start_date?.toString().slice(0, 10) ?? '',
    end_date:       props.purchaseOrder?.end_date?.toString().slice(0, 10)   ?? '',
    payment_term_id:props.purchaseOrder?.payment_term_id ?? '',
    internal_notes: props.purchaseOrder?.internal_notes ?? '',
    lines: props.purchaseOrder?.lines?.map(l => ({
        product_id:     l.product_id     ?? '',
        description:    l.description    ?? '',
        quantity:       l.quantity       ?? 1,
        uom_id:         l.uom_id         ?? '',
        unit_price:     l.unit_price     ?? 0,
        discount_pct:   l.discount_pct   ?? 0,
        tolerance_pct:  l.tolerance_pct  ?? 0,
        line_total:     l.line_total     ?? 0,
    })) ?? [{ product_id: '', description: '', quantity: 1, uom_id: '', unit_price: 0, discount_pct: 0, tolerance_pct: 0, line_total: 0 }],
})

const poTotal = computed(() => {
    return sumMoney(form.lines.map(l => l.line_total)) // Audit L6: exact (Utils/money.js)
})

// Auto-fills Payment Terms from the selected Supplier — only if the
// user hasn't already picked one manually (e.g. editing an existing
// PO, or already chose a different term on purpose). Fixed July 2026
// — this never existed before; the field was always left blank.
// The term follows the supplier, unless the user picked a term themselves.
let autoTermId = null
function onSupplierChange() {
    const supplier = (props.suppliers ?? []).find(s => s.id == form.partner_id)
    if (supplier && (!form.payment_term_id || String(form.payment_term_id) === String(autoTermId))) {
        form.payment_term_id = supplier.payment_term_id ?? ''
        autoTermId = supplier.payment_term_id ?? null
    }
}

// A foreign currency must not start at "1" and 0 is never a valid rate.
// Left empty, the server uses the rate table for the issuance date (or
// refuses with a clear message).
function onCurrencyChange() {
    form.exchange_rate = isForeignCurrency.value ? '' : '1'
}

function onProductChange(idx) {
    const line    = form.lines[idx]
    const product = (props.products ?? []).find(p => p.id == line.product_id)
    if (product) {
        // Fill description / unit only when empty OR still the value WE filled
        // for the previous product — never over something the user typed.
        if (!line.description || line.description === line._autoDesc) {
            line.description = product.name_en
            line._autoDesc = product.name_en
        }
        // Auto-fill with the product's PURCHASE unit (e.g. Carton),
        // not its internal storage unit — fixed July 2026. Falls back
        // to primary_uom_id only if no purchase-specific UOM is set
        // up for this product. Still fully overridable per line.
        const newUom = product.purchase_uom_id ?? product.primary_uom_id ?? ''
        if (!line.uom_id || line.uom_id === line._autoUom) {
            line.uom_id = newUom
            line._autoUom = newUom
        }
    }
    calcLine(idx)
}

function calcLine(idx) {
    const line  = form.lines[idx]
    // Audit L6: same rounding as the server's calcLineTotal() — see Utils/money.js
    line.line_total = discountedLineTotal(line.quantity, line.unit_price, line.discount_pct)
}

function addLine() {
    form.lines.push({ product_id: '', description: '', quantity: 1, uom_id: '', unit_price: 0, discount_pct: 0, tolerance_pct: 0, line_total: 0 })
}

function removeLine(idx) {
    form.lines.splice(idx, 1)
}

function submit() {
    // 0 (or negative) is never a valid exchange rate; empty = system rate.
    if (form.exchange_rate !== '' && form.exchange_rate !== null && !(Number(form.exchange_rate) > 0)) {
        form.setError('exchange_rate', t('accounting.purchaseOrders.form.exchangeRateInvalid'))
        return
    }
    form.clearErrors('exchange_rate')
    if (isEdit.value) {
        form.put(route('accounting.purchase-orders.update', props.purchaseOrder.id))
    } else {
        form.post(route('accounting.purchase-orders.store'))
    }
}

function fmt(val) {
    return Number(val || 0).toLocaleString('en-US', { minimumFractionDigits: 2, maximumFractionDigits: 2 })
}

function statusLabel(s) {
    const map = { draft: 'Draft', active: 'Active', on_hold: 'On Hold', closed: 'Closed', cancelled: 'Cancelled' }
    return map[s] ?? s
}
function receiptLabel(s) {
    const map = { not_received: 'Not Received', partially_received: 'Partially Received', fully_received: 'Fully Received' }
    return map[s] ?? s
}
function billingLabel(s) {
    const map = { not_billed: 'Not Billed', partially_billed: 'Partially Billed', fully_billed: 'Fully Billed' }
    return map[s] ?? s
}
</script>

