  here — they belong exclusively to the future Goods Receipt Note
  and Supplier Bill modules. This form only ever touches the PO's
  own `status` lifecycle field, same as Sales Order.

  @layout    AppLayout
  @route     accounting.purchase-orders.create / accounting.purchase-orders.edit
